"""Browser tests: checklist, scratchpad and reminders (no database: one JSON file)."""
import os, sys, tempfile, json, datetime
sys.path.insert(0, os.path.dirname(__file__))
from ui_common import *

PASS = FAIL = 0
SHOTS = "/tmp/ui/shots"; os.makedirs(SHOTS, exist_ok=True)
def check(name, cond, detail=""):
    global PASS, FAIL
    if cond: PASS += 1; print(f"  PASS  {name}")
    else: FAIL += 1; print(f"  FAIL  {name}  {str(detail)[:400]}")

d = tempfile.mkdtemp(); P = lambda n: os.path.join(d, n)
cfg = P("cfg"); os.makedirs(cfg); os.environ["KEMPT_CONFIG_DIR"] = cfg; os.environ["KEMPT_NO_TRAY"] = "1"; os.environ["XDG_CONFIG_HOME"] = P("xdg")
NF = os.path.join(cfg, "notes.json")
open(P("a.json"), "w").write('{"a":1}\n')
START = datetime.datetime(2026, 11, 7, 10, 0, tzinfo=datetime.timezone.utc)   # 15:30 IST

def local(ms):
    return datetime.datetime.fromtimestamp(ms / 1000).strftime("%Y-%m-%dT%H:%M")

with sync_playwright() as pw:
    browser = pw.chromium.launch()
    g = Gui([P("a.json")])
    ctx = browser.new_context(viewport={"width": 1100, "height": 800}, timezone_id="Asia/Kolkata", locale="en-US")
    pg = ctx.new_page(); errs = []; reqs = []
    pg.on("pageerror", lambda e: errs.append(str(e))); pg.on("console", lambda m: errs.append(m.text) if m.type == "error" else None)
    pg.on("request", lambda r: reqs.append(r.url))
    pg.add_init_script('''window.__osc = 0; window.__notes = [];
      window.AudioContext = class { constructor() { this.currentTime = 0; this.state = 'running'; this.destination = {}; } createOscillator() { window.__osc++; return { frequency: { value: 0 }, connect() {}, start() {}, stop() {}, type: '' }; } createGain() { return { gain: { setValueAtTime() {}, exponentialRampToValueAtTime() {} }, connect() {} }; } resume() {} };
      window.Notification = function (t, o) { window.__notes.push([t, o.body]); }; Notification.permission = 'granted'; Notification.requestPermission = () => Promise.resolve('granted');''')
    pg.clock.install(time=START)
    pg.goto(g.url); pg.wait_for_selector("#tabs .tab")
    items = lambda: pg.eval_on_selector_all(".nt .it .tx", "els => els.map(e => e.value)")

    print("== open")
    check("notes button in the top bar", pg.locator("#btn-notes").count() == 1)
    pg.click("#btn-notes"); pg.wait_for_selector(".nt .addrow")
    check("tab is named Checklist", "Checklist" in pg.inner_text("#tabs .tab.active"))
    pg.keyboard.press("Alt+j"); pg.wait_for_timeout(150)
    check("Alt+J does not open a second tab", pg.locator("#tabs .tab:has-text('Checklist')").count() == 1)
    check("empty state is explained", "first item" in pg.inner_text(".nt .list"))

    print("== items")
    for t in ("Buy milk", "Send report"): pg.fill(".nt .t", t); pg.press(".nt .t", "Enter")
    check("Enter adds items in order", items() == ["Buy milk", "Send report"], items())
    pg.locator(".nt .it input[type=checkbox]").first.click(); pg.wait_for_timeout(100)
    check("ticked item sinks below open ones and is struck through", items() == ["Send report", "Buy milk"] and pg.locator(".nt .it.done").count() == 1, items())
    pg.fill(".nt .it:first-child .tx", "Send the report"); pg.press(".nt .it:first-child .tx", "Tab"); pg.wait_for_timeout(100)
    check("text edits in place", items()[0] == "Send the report", items())
    pg.click(".nt .clr"); pg.wait_for_timeout(100)
    check("Clear done removes ticked items", items() == ["Send the report"], items())

    print("== reminder fires on time")
    due = int((START + datetime.timedelta(minutes=5)).timestamp() * 1000)
    pg.fill(".nt .t", "Call Ann"); pg.fill(".nt .w", local(due)); pg.click(".nt .go"); pg.wait_for_timeout(150)
    check("reminder chip shows its time", pg.locator(".nt .it .when input").count() == 1 and pg.input_value(".nt .it .when input") == local(due))
    check("one timer is armed", pg.evaluate("Notes.timer") != 0)
    pg.evaluate("Notes.caps = {}")   # as if the program had no sound/notification helper: the page does both itself
    pg.clock.run_for(4 * 60 * 1000); pg.wait_for_timeout(100)
    check("nothing fires before the time", pg.locator(".toast.remind").count() == 0)
    pg.clock.run_for(70 * 1000); pg.wait_for_selector(".toast.remind", timeout=3000)
    check("reminder popup appears with the item text", "Call Ann" in pg.inner_text(".toast.remind"))
    check("a sound plays: three tones", pg.evaluate("window.__osc") == 3, pg.evaluate("window.__osc"))
    check("a desktop notification is shown with the item text", pg.evaluate("window.__notes") == [["Kempt reminder", "Call Ann"]], pg.evaluate("window.__notes"))
    check("badge counts it", pg.inner_text("#btn-notes .nb") == "1" and pg.locator("#btn-notes .nb").is_visible())
    check("item is highlighted as due", pg.locator(".nt .it.due").count() == 1)
    check("no timer is left once nothing is pending", pg.evaluate("Notes.timer") == 0, pg.evaluate("Notes.timer"))
    pg.click(".toast.remind .sn"); pg.wait_for_timeout(150)
    check("Snooze pushes it 10 minutes out and re-arms", pg.locator(".toast.remind").count() == 0 and pg.evaluate("Notes.timer") != 0 and pg.locator("#btn-notes .nb").is_hidden())
    pg.clock.run_for(int(10.1 * 60 * 1000)); pg.wait_for_selector(".toast.remind", timeout=3000)
    r = pg.evaluate("""() => { Notes.caps = { os: true, sound: true }; const o = window.__osc, n = window.__notes.length; Notes.fire({ id: 'probe', t: 'Probe', done: false, due: Date.now() }); const r = [window.__osc - o, window.__notes.length - n]; Notes.items = Notes.items.filter(i => i.id !== 'probe'); [...document.querySelectorAll('.toast.remind')].pop().remove(); return r; }""")
    check("when the program announces reminders itself, the page stays silent (no double sound or notification)", r == [0, 0], r)
    pg.evaluate("Notes.caps = {}")
    pg.evaluate("prefs.set('sound', false)"); n0 = pg.evaluate("window.__osc")
    pg.click(".toast.remind .dn"); pg.wait_for_timeout(150)
    check("Done ticks the item and clears the badge", pg.locator(".nt .it.done").count() == 1 and pg.locator("#btn-notes .nb").is_hidden())

    pg.click("#btn-settings"); pg.click(".s-nav [data-p=startup]"); pg.wait_for_selector("#set-sound")
    check("Settings has the sound option", pg.is_checked("#set-sound") is False)
    pg.check("#set-sound"); pg.click("#set-snd-test"); pg.wait_for_timeout(100)
    check("Test button plays the sound", pg.evaluate("window.__osc") == n0 + 3, (pg.evaluate("window.__osc"), n0))
    pg.keyboard.press("Escape"); pg.wait_for_timeout(150)

    print("== scratchpad and saving")
    pg.fill(".nt .pad", "line one\nline two"); pg.wait_for_timeout(900)
    saved = json.load(open(NF))
    check("notes.json holds items and pad", saved["pad"] == "line one\nline two" and len(saved["items"]) == 2, saved)
    check("file is small", os.path.getsize(NF) < 2000, os.path.getsize(NF))
    pg.reload(); pg.wait_for_selector("#tabs .tab"); pg.click("#btn-notes"); pg.wait_for_selector(".nt .pad")
    check("everything survives a reload", pg.input_value(".nt .pad") == "line one\nline two" and "Send the report" in items())
    pg.screenshot(path=f"{SHOTS}/notes.png")

    print("== reminders missed while closed")
    json.dump({"items": [{"id": "x1", "t": "Pay rent", "done": False, "due": int(START.timestamp() * 1000) - 3600000, "fired": False},
                         {"id": "x2", "t": "Later", "done": False, "due": int(START.timestamp() * 1000) + 86400000, "fired": False}], "pad": ""}, open(NF, "w"))
    pg.reload(); pg.wait_for_selector(".toast", timeout=5000)
    check("on start the missed one is reported", "Pay rent" in pg.inner_text("#toasts"), pg.inner_text("#toasts"))
    check("badge shows 1 and the future one has a timer", pg.inner_text("#btn-notes .nb") == "1" and pg.evaluate("Notes.timer") != 0)

    check("no JS errors so far", not errs, errs)
    print("== start at login and own window (Settings)")
    pg.click("#btn-settings"); pg.click(".s-nav [data-p=startup]"); pg.wait_for_selector("#set-autostart")
    check("start-at-login is off at first", pg.is_checked("#set-autostart") is False)
    pg.check("#set-autostart"); pg.wait_for_timeout(500)
    desk = P("xdg/autostart/kempt.desktop")
    check("ticking it creates the autostart entry", os.path.exists(desk) and "gui --background" in open(desk).read())
    pg.uncheck("#set-autostart"); pg.wait_for_timeout(500)
    check("unticking removes it", not os.path.exists(desk))
    pg.check("#set-appwin"); pg.wait_for_timeout(700)
    check("own-window choice is saved", json.load(open(os.path.join(cfg, "state.json"))).get("appwin") is True)
    pg.uncheck("#set-appwin"); pg.keyboard.press("Escape"); pg.wait_for_timeout(200)
    print("== opened from the tray or a second launch")
    base = pg.url.split("&")[0]
    pg.goto(base + "&view=notes"); pg.wait_for_selector(".nt .addrow")
    check("?view=notes opens the checklist", "Checklist" in pg.inner_text("#tabs .tab.active"))
    check("and tidies the address", "view=" not in pg.url, pg.url)
    pg.goto(base + "&open=" + P("a.json")); pg.wait_for_selector("#tabs .tab:has-text('a.json')", timeout=5000)
    check("?open=<file> opens that file", True)

    print("== repeating reminders")
    pg.click("#btn-notes"); pg.wait_for_selector(".nt .addrow"); pg.wait_for_timeout(100)
    def addrep(text, when, rep):
        pg.fill(".nt .t", text); pg.fill(".nt .w", when); pg.select_option(".nt .rp", rep); pg.click(".nt .go"); pg.wait_for_timeout(100)
    row = lambda t: pg.locator('.nt .it').nth(items().index(t))
    mit = lambda t: pg.evaluate("t => { const i = Notes.items.find(a => a.t === t && !a.k); return i ? { due: i.due, rep: i.rep, base: i.base, fired: i.fired } : null; }", t)
    occ = lambda t: pg.evaluate("t => Notes.items.filter(a => a.k === 'occ' && a.t === t).map(a => a.due)", t)
    addrep("Standup", "2026-11-09T09:00", "weekdays")
    check("a repeat is chosen next to the reminder time", pg.locator(".nt .addrow .rp").count() == 1 and mit("Standup")["rep"] == "weekdays")
    o = occ("Standup")
    check("the next 22 weekdays are stored ahead of time, hidden from the list", len(o) == 22 and "Standup" not in [x for x in items() if x != "Standup"] and items().count("Standup") == 1, (len(o), items()))
    days = [datetime.datetime.fromtimestamp(x / 1000).weekday() for x in o]
    check("weekday repeats skip Saturday and Sunday", all(x < 5 for x in days) and local(o[0]) == "2026-11-10T09:00" and local(o[4]) == "2026-11-16T09:00", [local(x) for x in o[:6]])
    addrep("Backup", "2026-11-08T21:00", "daily"); check("daily: 30 ahead, one per day", len(occ("Backup")) == 30 and local(occ("Backup")[0]) == "2026-11-09T21:00")
    addrep("Rent", "2026-12-31T09:00", "monthly")
    check("monthly clamps to the last day (31st -> Feb 28)", [local(x)[:10] for x in occ("Rent")[:3]] == ["2027-01-31", "2027-02-28", "2027-03-31"], [local(x) for x in occ("Rent")[:3]])
    addrep("Review", "2026-11-12T10:00", "weekly"); check("weekly: same weekday, 13 ahead", len(occ("Review")) == 13 and local(occ("Review")[0]) == "2026-11-19T10:00")
    pg.clock.run_for(1000); disk = json.load(open(NF))["items"]
    check("all of them are on disk (so the program can announce them with no page open)", sum(1 for i in disk if i.get("k") == "occ") == 22 + 30 + 12 + 13 and all("p" in i for i in disk if i.get("k") == "occ"))
    row('Standup').locator('.rps').select_option("daily"); pg.wait_for_timeout(100)
    check("changing the repeat rebuilds the hidden reminders", len(occ("Standup")) == 30 and mit("Standup")["rep"] == "daily")
    row('Standup').locator('.rps').select_option("weekdays"); pg.wait_for_timeout(100)
    row('Standup').locator('input[type=checkbox]').click(); pg.wait_for_timeout(150)
    check("ticking a repeating item moves it to the next time instead of finishing it", local(mit("Standup")["due"]) == "2026-11-10T09:00" and not pg.evaluate("Notes.items.find(a => a.t === 'Standup' && !a.k).done"))
    pg.clock.run_for("48:00:00"); pg.wait_for_timeout(200)
    check("after its time passes the item rolls on by itself (checked each hour)", mit("Standup")["due"] > pg.evaluate("Date.now()") and not mit("Standup")["fired"], mit("Standup"))
    check("occurrences that have passed are cleaned up", pg.evaluate("Notes.items.filter(a => a.k === 'occ' && a.due < Date.now()).length") == 0 and len(occ("Standup")) == 22)
    row('Rent').locator('.x').click(); pg.wait_for_timeout(150)
    check("deleting a repeating item removes its hidden reminders", len(occ("Rent")) == 0 and mit("Rent") is None)
    row('Review').locator('.clrr').click(); pg.wait_for_timeout(150)
    check("clearing the reminder time also stops the repeat", len(occ("Review")) == 0 and mit("Review")["rep"] is None)
    check("hidden occurrences never show in the checklist or the badge", len(items()) == len(set(items())) and not any(i.get("k") for i in [] ) and pg.evaluate("Notes.items.filter(a => !a.k).length") == len(items()))

    print("== work and personal")
    nc = lambda: pg.evaluate("Notes.items.filter(a => !a.k).map(a => [a.t, a.c || ''])")
    pg.click("#btn-notes"); pg.wait_for_selector(".nt .addrow")
    check("the add row has a Work / Personal choice (Work by default)", pg.locator(".nt .addrow .cat option").count() == 2 and pg.input_value(".nt .addrow .cat") == "w")
    pg.fill(".nt .t", "Quarterly report"); pg.click(".nt .go"); pg.select_option(".nt .addrow .cat", "p"); pg.fill(".nt .t", "Call mum"); pg.click(".nt .go"); pg.wait_for_timeout(150)
    check("new items remember their category", ["Quarterly report", "w"] in nc() and ["Call mum", "p"] in nc(), nc())
    seg = lambda: pg.eval_on_selector_all(".nt .seg button", "e => e.map(b => [b.dataset.f, b.getAttribute('aria-pressed'), b.textContent])")
    check("All / Work / Personal filter with counts", [x[0] for x in seg()] == ["", "w", "p"] and seg()[0][1] == "true" and "Work" in seg()[1][2], seg())
    pg.click(".nt .seg button[data-f=w]"); pg.wait_for_timeout(100)
    check("Work shows only work items", pg.locator(".nt .it").count() == pg.evaluate("Notes.items.filter(a => !a.k && a.c === 'w').length") and "Quarterly report" in items() and "Call mum" not in items(), items())
    check("and the next item added starts as Work", pg.input_value(".nt .addrow .cat") == "w")
    pg.click(".nt .seg button[data-f=p]"); pg.wait_for_timeout(100)
    check("Personal shows only personal ones, and the add row follows", "Call mum" in items() and "Quarterly report" not in items() and pg.input_value(".nt .addrow .cat") == "p")
    pg.locator(".nt .it").first.locator(".cs").select_option("w"); pg.wait_for_timeout(150)
    check("an item can be moved to the other category", ["Call mum", "w"] in nc() and "Call mum" not in items(), nc())
    pg.click(".nt .seg button[data-f=w]"); pg.wait_for_timeout(100)
    row("Call mum").locator("input[type=checkbox]").click(); pg.click(".nt .seg button[data-f=p]"); pg.click(".nt .clr"); pg.wait_for_timeout(100)
    check("'Clear done' only clears what the filter shows", ["Call mum", "w"] in nc(), nc())
    pg.click(".nt .seg button[data-f=w]"); pg.click(".nt .clr"); pg.wait_for_timeout(100)
    check("...and clears it when that category is shown", ["Call mum", "w"] not in nc())
    pg.reload(); pg.wait_for_selector("#tabs .tab"); pg.click("#btn-notes"); pg.wait_for_selector(".nt .seg")
    check("the filter is remembered across a reload", pg.eval_on_selector(".nt .seg button[data-f=w]", "b => b.getAttribute('aria-pressed')") == "true")
    pg.click(".nt .seg button[data-f='']"); pg.wait_for_timeout(100)
    check("old items with no category still show under All", pg.evaluate("() => { Notes.items.push({ id: 'old1', t: 'Old item', done: false, due: null, fired: false }); Notes.save(); return true; }") and pg.evaluate("() => { actions.notes(); return true; }"))
    pg.evaluate("() => { Tabs.list.find(x => x.kind === 'notes').render(); }"); check("(no category = a dash in the item's menu)", "Old item" in items() and row("Old item").locator(".cs").input_value() == "")
    pg.evaluate("() => { Notes.items = Notes.items.filter(a => a.id !== 'old1'); Notes.save(); Tabs.list.find(x => x.kind === 'notes').render(); }")

    print("== cost and safety")
    check("a 64 KB+ note is accepted (own 512 KB budget)", pg.evaluate("""async () => { try { await api('notes/set', { patch: { pad: 'x'.repeat(200000) } }); return true; } catch (e) { return e.message; } }"""))
    check("oversized notes are refused, not truncated", pg.evaluate("""async () => { try { await api('notes/set', { patch: { pad: 'x'.repeat(600000) } }); return 'accepted'; } catch (e) { return 'refused'; } }""") == "refused")
    check("unknown keys are ignored", pg.evaluate("""async () => { await api('notes/set', { patch: { evil: 1 } }); const j = await api('notes/get'); return 'evil' in j; }""") is False)
    ext = [u for u in reqs if not u.startswith(g.url.split("/?")[0]) and not u.startswith("data:") and not u.startswith("blob:")]
    check("no request left this computer", not ext, ext)
    ctx.close(); g.stop()
print(f"\n{PASS} passed, {FAIL} failed"); sys.exit(1 if FAIL else 0)
